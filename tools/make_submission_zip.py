"""Make the submission zip: a complete package to reproduce the final render, plus the source.

Zip layout (top folder: renderman-challenge-paper-soul/):
  HOW_TO_RENDER.txt      how to reproduce the final image
  render_package/        the render-ready scene from the RANCHecker .vub: the self-contained
                         .blend, all textures (.tex) and the OSL shader, paths relative to the scene
  final/                 the final 4K render
  source/                the repo (scripts, scenes, progress images, docs), without assets/ (the
                         challenge's own downloads and files regenerated from them) and build/

Usage (plain Python):
  python3 tools/make_submission_zip.py build/cloud/paper_soul_v007.vub [out.zip] [--no-git]
  (default out: build/submission/renderman-challenge-paper-soul.zip)
"""

import os
import shutil
import sys
import zipfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOP = "renderman-challenge-paper-soul"  # folder name inside the zip
FINAL = os.path.join(REPO, "outputs", "v003_chochin_lantern_cloud.png")
SKIP_DIRS = {"assets", "build"}  # at the repo root
SKIP_NAMES = {".DS_Store"}
SKIP_SUFFIXES = (".blend1", "_black.png", ".zip",  # backups and derived posting copies
                 "_render.blend")  # the self-contained render scene: already in render_package/
STORED = (".png", ".jpg", ".jpeg", ".tex", ".zip", ".exr")  # already compressed: don't recompress
VUB_KEEP_DIRS = ("textures/", "shaders/")  # plus the .blend; RANCHecker bookkeeping files are left out

HOW_TO = """Paper Soul -- RenderMan "Diorama Drama" Art Challenge (finalist), by Li-Yi Wei

Reproducing the final render (final/{final}):

1. Software: Blender 4.5 LTS with RenderMan for Blender 27.3 (RenderMan Pro Server 27.3).
   On Apple Silicon, RenderMan needs the Intel (x64) build of Blender, and XPU is not
   available on macOS (it falls back to RIS); the final image was rendered with XPU on
   Ranch Computing's cloud farm (CPU).
2. Open render_package/{blend}. It is self-contained: all textures are in
   render_package/textures/ and the OSL shader in render_package/shaders/, referenced
   relative to the scene (<blend_dir>/...). Keep the three together.
3. The scene is already set up: RenderMan XPU, 3840x2160 at 100%, frame 1,
   64-512 samples, pixel variance 0.02. Render frame 1, e.g. headless:
     blender -b render_package/{blend} --addons RenderManForBlender -f 1
   (RenderMan writes the image under build/final/ next to render_package/.)

The final PNG is 16-bit RGBA with a transparent background; the posted versions are
flattened onto black (source/tools/flatten_png.py).

How the scene was built: source/README.md. Everything is generated by scripts in source/tools/
from the challenge's original asset downloads (not included): Oni props converted from the
.usda/.abc files, RenderMan materials for the KitBash3D set and the BigMediumSmall character,
the newspaper fracture shader (source/shaders/PaperFracture.osl), and the layout, lighting and
camera. Ideation and decision notes: source/diorama-drama.md. The pipeline was scripted with
Claude Code, an AI coding agent; story, composition and art direction by Li-Yi Wei.

Assets by BigMediumSmall, KitBash3D, Netflix, and Pixar. RenderMan 'Diorama Drama' Art
Challenge (c) Disney/Pixar. Cloud rendering by Ranch Computing.
"""


def add(zf, path, arcname):
    method = zipfile.ZIP_STORED if path.lower().endswith(STORED) else zipfile.ZIP_DEFLATED
    zf.write(path, arcname, compress_type=method)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args or not args[0].endswith(".vub"):
        raise SystemExit(__doc__)
    vub = os.path.abspath(args[0])
    out = os.path.abspath(args[1] if len(args) > 1 else
                          os.path.join(REPO, "build", "submission", "renderman-challenge-paper-soul.zip"))
    skip = SKIP_DIRS | ({".git"} if "--no-git" in sys.argv else set())
    os.makedirs(os.path.dirname(out), exist_ok=True)

    with zipfile.ZipFile(out, "w", allowZip64=True) as zf, zipfile.ZipFile(vub) as package:
        # The render package, copied entry by entry out of the .vub.
        blend = None
        for info in package.infolist():
            if info.is_dir() or not (info.filename.endswith(".blend") or info.filename.startswith(VUB_KEEP_DIRS)):
                continue
            if info.filename.endswith(".blend"):
                blend = info.filename
            entry = zipfile.ZipInfo(f"{TOP}/render_package/{info.filename}", info.date_time)
            entry.compress_type = zipfile.ZIP_STORED if info.filename.lower().endswith(STORED) else zipfile.ZIP_DEFLATED
            with package.open(info) as src, zf.open(entry, "w", force_zip64=True) as dst:
                shutil.copyfileobj(src, dst, 1 << 20)
        if blend is None:
            raise SystemExit(f"no .blend in {vub}")
        # The final image and the instructions.
        add(zf, FINAL, f"{TOP}/final/{os.path.basename(FINAL)}")
        zf.writestr(f"{TOP}/HOW_TO_RENDER.txt", HOW_TO.format(final=os.path.basename(FINAL), blend=blend))
        # The source.
        for root, dirs, files in os.walk(REPO):
            if os.path.relpath(root, REPO) == ".":
                dirs[:] = [d for d in dirs if d not in skip]
            for name in sorted(files):
                if name in SKIP_NAMES or name.endswith(SKIP_SUFFIXES):
                    continue
                path = os.path.join(root, name)
                add(zf, path, f"{TOP}/source/{os.path.relpath(path, REPO)}")
        count = len(zf.namelist())
    print(f"{out}: {count} files, {os.path.getsize(out) / 1e9:.2f} GB (render package: {blend})")


main()
